#!/usr/bin/env python3
"""Writes docs/COVERAGE.md from manifest/coverage.json (run after generate.py).

  python3 gen/coverage_md.py [--coverage manifest/coverage.json] [--out docs/COVERAGE.md]
"""
import argparse
import json
import os

# what each reason the generator gives means, in a sentence
REASONS = {
    "operator or internal": "operators, and the moc-generated metaObject/qt_metacall family",
    "denied": "unsafe with any arguments, or would call around qtc's checks (see DENY_PAIRS in generate.py); "
              "metaObject() and tr() are counted here too",
    "instance method of a non-copyable value class": "the class can be neither copied into a value handle nor owned by one",
    "returns type not bindable safely": "the result cannot cross into C safely (a reference into a container, "
                                        "a bindable property, an iterator)",
    "raw pointer to a non-QObject type": "a pointer with no owner and no way to tell when it dies",
    "type not bindable safely": "a parameter type that cannot cross from C safely (private signal tags, iterators, "
                                "views into temporaries)",
    "returns a raw pointer": "a pointer to a non-QObject the caller would have to free or keep alive",
    "non-const reference (out parameter)": "an out-parameter by reference",
    "rvalue reference": "a parameter that would be moved from",
    "slot named by a string": "takes a receiver and a slot by name, which would let Qt call any method",
    "required raw buffer pointer": "a raw memory buffer and length",
    "variadic": "a C variadic function",
    "non-Qt type": "a type from outside Qt (std::, platform types)",
    "returns non-Qt type": "returns a type from outside Qt",
    "QObject by value": "a QObject passed by value",
    "constantarray": "a C array parameter",
}


def reason_text(r):
    if r in REASONS:
        return REASONS[r]
    for prefix, text in (("returns unknown class ", "returns a nested or private class"),
                         ("unknown class ", "a nested or private class"),
                         ("returns template ", "returns a template type"),
                         ("template ", "a template type")):
        if r.startswith(prefix):
            return text
    return r


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    ap = argparse.ArgumentParser()
    ap.add_argument("--coverage", default=os.path.join(root, "manifest", "coverage.json"))
    ap.add_argument("--out", default=os.path.join(root, "docs", "COVERAGE.md"))
    args = ap.parse_args()
    cov = json.load(open(args.coverage))
    t = cov["totals"]
    lines = ["# Coverage", "",
             "What of Qt %s's public API qtc binds, generated by `gen/coverage_md.py` from "
             "`manifest/coverage.json`. A method counts once per declaring class; overloads count separately."
             % cov["qt_version"], "",
             "| | |", "|---|---|",
             "| methods declared | {:,} |".format(t["methods_seen"]),
             "| methods bound | {:,} ({:.1f}%) |".format(t["methods_bound"], 100.0 * t["methods_bound"] / t["methods_seen"]),
             "| constructors bound | {:,} |".format(t.get("ctors_bound", 0)),
             "| classes with bindings | {:,} |".format(t.get("classes_bound", 0)),
             "", "Without operators and moc internals, which C cannot name anyway, the share bound is %.1f%%." % (
                 100.0 * t["methods_bound"] / (t["methods_seen"] - t.get("skip:operator or internal", 0))),
             "", "## By module", "",
             "| module | classes | methods | bound | share | constructors |",
             "|---|---:|---:|---:|---:|---:|"]
    for name in sorted(cov["modules"], key=lambda m: -cov["modules"][m]["methods_seen"]):
        m = cov["modules"][name]
        seen, bound = m["methods_seen"], m.get("methods_bound", 0)
        lines.append("| {} | {:,} | {:,} | {:,} | {:.0f}% | {:,} |".format(name, m.get("classes_bound", 0), seen, bound,
                                                                   100.0 * bound / seen if seen else 0, m.get("ctors_bound", 0)))
    lines += ["", "## Why methods are left out", "",
              "| reason | methods | | examples |", "|---|---:|---|---|"]
    merged = {}
    examples = {}
    for r, n in cov["skip_reasons"].items():
        key = reason_text(r)
        merged[key] = merged.get(key, 0) + n
        examples.setdefault(key, []).extend(cov.get("skip_examples", {}).get(r, []))
    for key, n in sorted(merged.items(), key=lambda kv: -kv[1]):
        ex = []
        for e in examples[key]:
            if e not in ex and not e.endswith(("::metaObject", "::tr", "::qt_metacast", "::qt_metacall")):
                ex.append(e)
        lines.append("| {} | {:,} | | {} |".format(key, n, ", ".join("`%s`" % e for e in ex[:3])))
    lines += ["", "[LIMITS.md](LIMITS.md) says what to use instead of what is left out.", ""]
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
